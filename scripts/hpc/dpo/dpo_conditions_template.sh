    python scripts/dpo/run_preference_pipeline.py \
      --adapter-path "${BASE_SFT_ADAPTER}" \
      --base-model "${BASE_MODEL}" \
      --pairs-dir "${JUDGE_UNION_PAIRS_DIR}" \
      --balanced-pairs-dir "${JUDGE_UNION_BALANCED_DIR}" \
      --dpo-output-dir "${JUDGE_UNION_DPO_OUTPUT}" \
      --epochs "${JUDGE_EPOCHS}" \
      --learning-rate "${LEARNING_RATE}" \
      --batch-size "${BATCH_SIZE}" \
      --grad-accum "${GRAD_ACCUM}" \
      --dpo-beta "${JUDGE_BETA}" \
      --attn-implementation "${ATTN_IMPL}" \
      --seed "${SEED}" \
      --wandb-project "${WANDB_PROJECT}" \
      --wandb-run "judge-union-dpo-${JUDGE_MODEL_SLUG}-beta${JUDGE_BETA}-seed${SEED}" \
      "${PIPELINE_CKPT_ARGS[@]}" \
      "${PIPELINE_RESTART_ARGS[@]}" \
      --skip-steps 1
    ;;

  ood_eval)
