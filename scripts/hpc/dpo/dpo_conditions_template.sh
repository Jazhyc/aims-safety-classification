#!/bin/bash
#SBATCH --job-name=dpo-cond
#SBATCH --time=02:00:00
#SBATCH --mem=32GB
#SBATCH --partition=gpu
#SBATCH --gpus-per-node=a100:1
#SBATCH --output=logs/slurm/%x-%j.out

set -euo pipefail

module --force purge
module load Python/3.12.3-GCCcore-13.3.0
module load CUDA/13.2.0

PROJECT_ROOT="${PROJECT_ROOT:-${SLURM_SUBMIT_DIR:-$PWD}}"
cd "${PROJECT_ROOT}"

source .venv/bin/activate
if [ -f "${HOME}/.wandb_secrets" ]; then
  # shellcheck disable=SC1090
  source "${HOME}/.wandb_secrets"
fi

export PYTHONUNBUFFERED=1
export HF_HUB_CACHE="${HF_HUB_CACHE:-/scratch/${USER}/huggingface_cache}"
# Reproducibility controls (can be overridden via sbatch --export)
export PYTHONHASHSEED="${PYTHONHASHSEED:-0}"
export CUBLAS_WORKSPACE_CONFIG="${CUBLAS_WORKSPACE_CONFIG:-:4096:8}"
export TOKENIZERS_PARALLELISM="${TOKENIZERS_PARALLELISM:-false}"
export CUDA_LAUNCH_BLOCKING="${CUDA_LAUNCH_BLOCKING:-0}"

STAGE="${STAGE:-}"
if [ -z "${STAGE}" ]; then
  echo "ERROR: STAGE is required."
  echo "Valid STAGE values: canonical | hard_dpo | judge_dpo | judge_gptoss | judge_standalone_dpo | judge_gptoss_standalone_dpo | judge_decent_dpo | union_decent_dpo | judge_union_dpo | ood_eval | ratio_dpo | curriculum_dpo | gemma_canonical | gemma_hard_dpo"
  exit 1
fi

# ---------------------------------------------------------------------------
# Shared defaults (override via sbatch --export)
# ---------------------------------------------------------------------------
BASE_MODEL="${BASE_MODEL:-meta-llama/Llama-3.1-8B-Instruct}"
BASE_SFT_ADAPTER="${BASE_SFT_ADAPTER:-Jazhyc/llama-3.1-8b-sft-generation}"
JUDGE_MODEL="${JUDGE_MODEL:-openai/gpt-oss-120b}"
JUDGE_MODEL_SLUG="${JUDGE_MODEL_SLUG:-${JUDGE_MODEL//\//_}}"
JUDGE_TENSOR_PARALLEL="${JUDGE_TENSOR_PARALLEL:-1}"
JUDGE_GPU_TYPE="${JUDGE_GPU_TYPE:-rtx_pro_6000}"

SEED="${SEED:-22}"
TEMPERATURE="${TEMPERATURE:-0.8}"
K_SAMPLES="${K_SAMPLES:-5}"
MAX_MODEL_LEN="${MAX_MODEL_LEN:-4096}"
EPOCHS="${EPOCHS:-2}"
LEARNING_RATE="${LEARNING_RATE:-5e-5}"
BATCH_SIZE="${BATCH_SIZE:-2}"
GRAD_ACCUM="${GRAD_ACCUM:-8}"
DPO_BETA="${DPO_BETA:-0.5}"
DPO_SAVE_STRATEGY="${DPO_SAVE_STRATEGY:-no}"
DPO_SAVE_STEPS="${DPO_SAVE_STEPS:-200}"
DPO_SAVE_TOTAL_LIMIT="${DPO_SAVE_TOTAL_LIMIT:-2}"
SELECT_BEST_OOD_CHECKPOINT="${SELECT_BEST_OOD_CHECKPOINT:-0}"
OOD_EVAL_GPU_MEMORY_UTILIZATION="${OOD_EVAL_GPU_MEMORY_UTILIZATION:-0.75}"
HARMFUL_WEIGHT="${HARMFUL_WEIGHT:-1.0}"
UNBALANCED="${UNBALANCED:-0}"
FORCE="${FORCE:-0}"
FORCE_FROM="${FORCE_FROM:-}"
ATTN_IMPL="${ATTN_IMPL:-sdpa}"
EVAL_LORA_RANK="${EVAL_LORA_RANK:-16}"

WANDB_PROJECT="${WANDB_PROJECT:-intention-jailbreak}"
# For ood_eval stage: path to the trained DPO adapter to evaluate.
# Set to the _adapter directory of whichever condition you want to assess.
OOD_EVAL_ADAPTER="${OOD_EVAL_ADAPTER:-}"
OOD_EVAL_OUTPUT="${OOD_EVAL_OUTPUT:-data/safety_experiment/ood_validation/dpo}"

# Condition paths
HARD_PAIRS_DIR="${HARD_PAIRS_DIR:-data/dpo_pairs/hard}"
HARD_BALANCED_DIR="${HARD_BALANCED_DIR:-data/dpo_pairs/hard_balanced}"
HARD_DPO_OUTPUT="${HARD_DPO_OUTPUT:-trained_models/causal/dpo-hard}"
# Canonical T=0.8 samples shared across all conditions for fair comparison.
# All conditions reuse these samples so only the filtering logic differs.
CANONICAL_SAMPLES="${CANONICAL_SAMPLES:-data/dpo_pairs/train_t0.8/parsed_samples.jsonl}"

JUDGE_PAIRS_DIR="${JUDGE_PAIRS_DIR:-data/dpo_pairs/judge}"
JUDGE_BALANCED_DIR="${JUDGE_BALANCED_DIR:-data/dpo_pairs/judge_balanced}"
JUDGE_DPO_OUTPUT="${JUDGE_DPO_OUTPUT:-trained_models/causal/dpo-judge}"
# Override epochs/beta for judge independently of the global EPOCHS/DPO_BETA.
# Falls back to global values when not set or empty.
JUDGE_EPOCHS="${JUDGE_EPOCHS:=${EPOCHS}}"
JUDGE_BETA="${JUDGE_BETA:=${DPO_BETA}}"
# Set to non-empty to skip sample generation and reuse cached parsed_samples.jsonl
JUDGE_FROM_SAMPLES="${JUDGE_FROM_SAMPLES:-}"

# judge_standalone_dpo: judge bad_match rejecteds only (no hard mislabels)
JUDGE_STANDALONE_PAIRS_DIR="${JUDGE_STANDALONE_PAIRS_DIR:-data/dpo_pairs/judge_standalone}"
JUDGE_STANDALONE_BALANCED_DIR="${JUDGE_STANDALONE_BALANCED_DIR:-data/dpo_pairs/judge_standalone_balanced}"
JUDGE_STANDALONE_DPO_OUTPUT="${JUDGE_STANDALONE_DPO_OUTPUT:-trained_models/causal/dpo-judge-standalone}"

# judge_decent_dpo: judge-only with bad_match + decent_match rejecteds
# Reuses pairs generated by judge_standalone_dpo (dpo_pairs_decent.jsonl)
JUDGE_DECENT_BALANCED_DIR="${JUDGE_DECENT_BALANCED_DIR:-data/dpo_pairs/judge_decent_balanced}"
JUDGE_DECENT_DPO_OUTPUT="${JUDGE_DECENT_DPO_OUTPUT:-trained_models/causal/dpo-judge-decent}"

# union_decent_dpo: hard ∪ judge (bad_match + decent_match)
# Reuses pairs generated by judge_dpo (dpo_pairs_decent.jsonl)
UNION_DECENT_BALANCED_DIR="${UNION_DECENT_BALANCED_DIR:-data/dpo_pairs/union_decent_balanced}"
UNION_DECENT_DPO_OUTPUT="${UNION_DECENT_DPO_OUTPUT:-trained_models/causal/dpo-union-decent}"

# judge_gptoss_standalone_dpo: GPT-OSS judge bad_match rejecteds only (no hard mislabels).
# GPT-OSS analogue of judge_standalone_dpo, for a clean standalone comparison.
JUDGE_GPTOSS_STANDALONE_PAIRS_DIR="${JUDGE_GPTOSS_STANDALONE_PAIRS_DIR:-data/dpo_pairs/judge_gptoss_standalone}"
JUDGE_GPTOSS_STANDALONE_BALANCED_DIR="${JUDGE_GPTOSS_STANDALONE_BALANCED_DIR:-data/dpo_pairs/judge_gptoss_standalone_balanced}"
JUDGE_GPTOSS_STANDALONE_DPO_OUTPUT="${JUDGE_GPTOSS_STANDALONE_DPO_OUTPUT:-trained_models/causal/dpo-judge-gptoss-standalone}"

# judge_union_dpo: union of bad_match verdicts from two judge models (gemma + GPT-OSS).
# Requires both judge_dpo and judge_gptoss runs to have completed (need judge_verdict
# saved in their parsed_samples.jsonl). Primary judge dir is JUDGE_PAIRS_DIR (gemma);
# second judge dir is JUDGE_GPTOSS_PAIRS_DIR (GPT-OSS).
JUDGE_GPTOSS_PAIRS_DIR="${JUDGE_GPTOSS_PAIRS_DIR:-data/dpo_pairs/judge_gptoss}"
JUDGE_UNION_PAIRS_DIR="${JUDGE_UNION_PAIRS_DIR:-data/dpo_pairs/judge_union}"
JUDGE_UNION_BALANCED_DIR="${JUDGE_UNION_BALANCED_DIR:-data/dpo_pairs/judge_union_balanced}"
JUDGE_UNION_DPO_OUTPUT="${JUDGE_UNION_DPO_OUTPUT:-trained_models/causal/dpo-judge-union}"

# ---------------------------------------------------------------------------
# Ratio sweep variables
# ---------------------------------------------------------------------------
# RATIO: fraction of judge pairs added on top of all hard pairs (0.0–1.0).
# Set per-job via sbatch --export. HARD_PAIRS_FILE and JUDGE_PAIRS_FILE must
# point to the pair sets produced by the canonical hard/judge stages.
RATIO="${RATIO:-0.5}"
RATIO_TAG="${RATIO_TAG:-${RATIO}}"   # e.g. "0.50" for directory names
RATIO_PAIRS_DIR="${RATIO_PAIRS_DIR:-data/dpo_pairs/ratio_${RATIO_TAG}}"
RATIO_BALANCED_DIR="${RATIO_BALANCED_DIR:-data/dpo_pairs/ratio_${RATIO_TAG}_balanced}"
RATIO_DPO_OUTPUT="${RATIO_DPO_OUTPUT:-trained_models/causal/dpo-ratio-${RATIO_TAG}}"
# Pair source files (defaults point to canonical hard/judge pair sets)
HARD_PAIRS_FILE="${HARD_PAIRS_FILE:-${HARD_PAIRS_DIR}/pairs_wrong_only.jsonl}"
JUDGE_PAIRS_FILE="${JUDGE_PAIRS_FILE:-${JUDGE_PAIRS_DIR}/pairs_judge_bad_only.jsonl}"

# ---------------------------------------------------------------------------
# Curriculum training variables
# ---------------------------------------------------------------------------
# Continuation-only curriculum:
#   Start from an existing hard-DPO adapter and continue on judge pairs.
#   Reference stays at SFT (--adapter-path); policy warm-starts from
#   --policy-adapter (CURRICULUM_POLICY_ADAPTER).
PHASE2_EPOCHS="${PHASE2_EPOCHS:-3}"
CURRICULUM_OUTPUT="${CURRICULUM_OUTPUT:-trained_models/causal/dpo-curriculum}"
CURRICULUM_POLICY_ADAPTER="${CURRICULUM_POLICY_ADAPTER:-}"

# ---------------------------------------------------------------------------
# Gemma DPO variables
# ---------------------------------------------------------------------------
GEMMA_BASE_MODEL="${GEMMA_BASE_MODEL:-google/gemma-3-12b-it}"
# Set to the merged SFT model HF ID (full weights) or a LoRA adapter ID.
# If GEMMA_NO_LORA=1 the pair generation step loads the model directly without LoRA.
GEMMA_SFT_ADAPTER="${GEMMA_SFT_ADAPTER:-Jazhyc/gemma-3-12b-intent-jailbreak-classifier-sft}"
GEMMA_NO_LORA="${GEMMA_NO_LORA:-0}"
GEMMA_CANONICAL_SAMPLES="${GEMMA_CANONICAL_SAMPLES:-data/dpo_pairs/gemma_train_t0.8/parsed_samples.jsonl}"
GEMMA_HARD_PAIRS_DIR="${GEMMA_HARD_PAIRS_DIR:-data/dpo_pairs/gemma_hard}"
GEMMA_HARD_BALANCED_DIR="${GEMMA_HARD_BALANCED_DIR:-data/dpo_pairs/gemma_hard_balanced}"
GEMMA_HARD_DPO_OUTPUT="${GEMMA_HARD_DPO_OUTPUT:-trained_models/causal/dpo-gemma-hard}"

echo "======================================================================"
echo " Preference Condition Stage"
echo "  Stage       : ${STAGE}"
echo "  Project root: ${PROJECT_ROOT}"
echo "  Base model  : ${BASE_MODEL}"
echo "======================================================================"

PIPELINE_RESTART_ARGS=()
if [ "${FORCE}" = "1" ]; then
  PIPELINE_RESTART_ARGS+=(--force)
fi
if [ -n "${FORCE_FROM}" ]; then
  PIPELINE_RESTART_ARGS+=(--force-from "${FORCE_FROM}")
fi

PIPELINE_CKPT_ARGS=(
  --dpo-save-strategy "${DPO_SAVE_STRATEGY}"
  --dpo-save-total-limit "${DPO_SAVE_TOTAL_LIMIT}"
)
if [ "${DPO_SAVE_STRATEGY}" = "steps" ]; then
  PIPELINE_CKPT_ARGS+=(--dpo-save-steps "${DPO_SAVE_STEPS}")
fi
if [ "${SELECT_BEST_OOD_CHECKPOINT}" = "1" ]; then
  PIPELINE_CKPT_ARGS+=(--select-best-ood-checkpoint)
  PIPELINE_CKPT_ARGS+=(--ood-eval-gpu-memory-utilization "${OOD_EVAL_GPU_MEMORY_UTILIZATION}")
fi

TRAIN_CKPT_ARGS=(
  --save-strategy "${DPO_SAVE_STRATEGY}"
  --save-total-limit "${DPO_SAVE_TOTAL_LIMIT}"
)
if [ "${DPO_SAVE_STRATEGY}" = "steps" ]; then
  TRAIN_CKPT_ARGS+=(--save-steps "${DPO_SAVE_STEPS}")
fi
if [ "${SELECT_BEST_OOD_CHECKPOINT}" = "1" ]; then
  TRAIN_CKPT_ARGS+=(--select-best-ood-checkpoint)
  TRAIN_CKPT_ARGS+=(--ood-eval-gpu-memory-utilization "${OOD_EVAL_GPU_MEMORY_UTILIZATION}")
fi

case "${STAGE}" in
  canonical)
    # Generate shared T=0.8 samples once. Every other condition uses
    # --from-samples pointing here so they never re-run the SFT model.
    if [ -f "${CANONICAL_SAMPLES}" ]; then
      echo "[SKIP] Canonical samples already exist at ${CANONICAL_SAMPLES}"
      exit 0
    fi
    # Derive output dir from CANONICAL_SAMPLES path
    CANONICAL_OUT_DIR="$(dirname "${CANONICAL_SAMPLES}")"
    python scripts/dpo/generate_dpo_pairs.py \
      --adapter-path "${BASE_SFT_ADAPTER}" \
      --base-model "${BASE_MODEL}" \
      --output-dir "${CANONICAL_OUT_DIR}" \
      --num-samples "${K_SAMPLES}" \
      --temperature "${TEMPERATURE}" \
      --max-model-len "${MAX_MODEL_LEN}" \
      --seed "${SEED}"
    ;;

  hard_dpo)
    HARD_SKIP_STEPS=""
    HARD_EXTRA_ARGS=()
    if [ "${UNBALANCED}" = "1" ]; then
      # Skip balancing step; use harmful_weight in loss instead
      HARD_SKIP_STEPS="2"
      HARD_EXTRA_ARGS+=(--unbalanced --harmful-weight "${HARMFUL_WEIGHT}")
    fi
    python scripts/dpo/run_preference_pipeline.py \
      --adapter-path "${BASE_SFT_ADAPTER}" \
      --base-model "${BASE_MODEL}" \
      --pairs-dir "${HARD_PAIRS_DIR}" \
      --balanced-pairs-dir "${HARD_BALANCED_DIR}" \
      --dpo-output-dir "${HARD_DPO_OUTPUT}" \
      --from-samples "${CANONICAL_SAMPLES}" \
      --temperature "${TEMPERATURE}" \
      --k-samples "${K_SAMPLES}" \
      --max-model-len "${MAX_MODEL_LEN}" \
      --epochs "${EPOCHS}" \
      --learning-rate "${LEARNING_RATE}" \
      --batch-size "${BATCH_SIZE}" \
      --grad-accum "${GRAD_ACCUM}" \
      --dpo-beta "${DPO_BETA}" \
      --attn-implementation "${ATTN_IMPL}" \
      --seed "${SEED}" \
      --wandb-project "${WANDB_PROJECT}" \
      --wandb-run "hard-dpo-beta${DPO_BETA}-seed${SEED}" \
      "${PIPELINE_CKPT_ARGS[@]}" \
      "${PIPELINE_RESTART_ARGS[@]}" \
      "${HARD_EXTRA_ARGS[@]}" \
      ${HARD_SKIP_STEPS:+--skip-steps "${HARD_SKIP_STEPS}"}
    ;;

  judge_dpo)
    # Two-pass judge flow.
    # Pass 1: always reuse canonical T=0.8 samples (generated once by hard_dpo or
    # train_t0.8 stage) so all conditions start from identical base samples.
    # JUDGE_FROM_SAMPLES is kept for backwards compatibility but is now redundant
    # since we always point at CANONICAL_SAMPLES.
    if [ -z "${JUDGE_FROM_SAMPLES}" ]; then
      echo "[judge_dpo] Reusing canonical samples from ${CANONICAL_SAMPLES}"
    else
      echo "[judge_dpo] JUDGE_FROM_SAMPLES set — reusing ${JUDGE_PAIRS_DIR}/parsed_samples.jsonl"
    fi

    python scripts/dpo/generate_dpo_pairs.py \
      --from-samples "${CANONICAL_SAMPLES}" \
      --adapter-path "${BASE_SFT_ADAPTER}" \
      --base-model "${BASE_MODEL}" \
      --output-dir "${JUDGE_PAIRS_DIR}" \
      --intent-filter \
      --judge-model "${JUDGE_MODEL}" \
      --judge-tensor-parallel "${JUDGE_TENSOR_PARALLEL}" \
      --max-model-len "${MAX_MODEL_LEN}"

    python scripts/dpo/run_preference_pipeline.py \
      --adapter-path "${BASE_SFT_ADAPTER}" \
      --base-model "${BASE_MODEL}" \
      --pairs-dir "${JUDGE_PAIRS_DIR}" \
      --balanced-pairs-dir "${JUDGE_BALANCED_DIR}" \
      --dpo-output-dir "${JUDGE_DPO_OUTPUT}" \
      --epochs "${JUDGE_EPOCHS}" \
      --learning-rate "${LEARNING_RATE}" \
      --batch-size "${BATCH_SIZE}" \
      --grad-accum "${GRAD_ACCUM}" \
      --dpo-beta "${JUDGE_BETA}" \
      --attn-implementation "${ATTN_IMPL}" \
      --seed "${SEED}" \
      --wandb-project "${WANDB_PROJECT}" \
      --wandb-run "judge-dpo-${JUDGE_MODEL_SLUG}-beta${JUDGE_BETA}-seed${SEED}" \
      "${PIPELINE_CKPT_ARGS[@]}" \
      "${PIPELINE_RESTART_ARGS[@]}" \
      --skip-steps 1
    ;;

  judge_gptoss)
    # Same flow as judge_dpo but using GPT-OSS as the judge model.
    # Outputs to JUDGE_GPTOSS_PAIRS_DIR so judge_union_dpo can merge verdicts.
    # GPT-OSS 120B needs the RTX Pro 6000 (96 GB) — override GPU at submit time if needed.
    GPTOSS_JUDGE_MODEL="${GPTOSS_JUDGE_MODEL:-openai/gpt-oss-120b}"
    GPTOSS_JUDGE_MODEL_SLUG="${GPTOSS_JUDGE_MODEL//\//_}"
    GPTOSS_JUDGE_TP="${GPTOSS_JUDGE_TP:-1}"

    python scripts/dpo/generate_dpo_pairs.py \
      --from-samples "${CANONICAL_SAMPLES}" \
      --adapter-path "${BASE_SFT_ADAPTER}" \
      --base-model "${BASE_MODEL}" \
      --output-dir "${JUDGE_GPTOSS_PAIRS_DIR}" \
      --intent-filter \
      --judge-model "${GPTOSS_JUDGE_MODEL}" \
      --judge-tensor-parallel "${GPTOSS_JUDGE_TP}" \
      --max-model-len "${MAX_MODEL_LEN}"

    python scripts/dpo/run_preference_pipeline.py \
      --adapter-path "${BASE_SFT_ADAPTER}" \
      --base-model "${BASE_MODEL}" \
      --pairs-dir "${JUDGE_GPTOSS_PAIRS_DIR}" \
      --balanced-pairs-dir "${JUDGE_UNION_BALANCED_DIR/_balanced/_gptoss_balanced}" \
      --dpo-output-dir "trained_models/causal/dpo-judge-gptoss" \
      --epochs "${JUDGE_EPOCHS}" \
      --learning-rate "${LEARNING_RATE}" \
      --batch-size "${BATCH_SIZE}" \
      --grad-accum "${GRAD_ACCUM}" \
      --dpo-beta "${JUDGE_BETA}" \
      --attn-implementation "${ATTN_IMPL}" \
      --seed "${SEED}" \
      --wandb-project "${WANDB_PROJECT}" \
      --wandb-run "judge-gptoss-dpo-${GPTOSS_JUDGE_MODEL_SLUG}-beta${JUDGE_BETA}-seed${SEED}" \
      "${PIPELINE_CKPT_ARGS[@]}" \
      "${PIPELINE_RESTART_ARGS[@]}" \
      --skip-steps 1
    ;;

  judge_standalone_dpo)
    # Judge-only condition: rejecteds = bad_match samples only, no hard mislabels.
    # Generates both dpo_pairs.jsonl (bad only) and dpo_pairs_decent.jsonl (bad+decent)
    # so judge_decent_dpo can reuse these pairs without a second generation pass.
    python scripts/dpo/generate_dpo_pairs.py \
      --from-samples "${CANONICAL_SAMPLES}" \
      --adapter-path "${BASE_SFT_ADAPTER}" \
      --base-model "${BASE_MODEL}" \
      --output-dir "${JUDGE_STANDALONE_PAIRS_DIR}" \
      --intent-filter \
      --judge-only \
      --judge-model "${JUDGE_MODEL}" \
      --judge-tensor-parallel "${JUDGE_TENSOR_PARALLEL}" \
      --max-model-len "${MAX_MODEL_LEN}"

    python scripts/dpo/run_preference_pipeline.py \
      --adapter-path "${BASE_SFT_ADAPTER}" \
      --base-model "${BASE_MODEL}" \
      --pairs-dir "${JUDGE_STANDALONE_PAIRS_DIR}" \
      --balanced-pairs-dir "${JUDGE_STANDALONE_BALANCED_DIR}" \
      --dpo-output-dir "${JUDGE_STANDALONE_DPO_OUTPUT}" \
      --epochs "${JUDGE_EPOCHS}" \
      --learning-rate "${LEARNING_RATE}" \
      --batch-size "${BATCH_SIZE}" \
      --grad-accum "${GRAD_ACCUM}" \
      --dpo-beta "${JUDGE_BETA}" \
      --attn-implementation "${ATTN_IMPL}" \
      --seed "${SEED}" \
      --wandb-project "${WANDB_PROJECT}" \
      --wandb-run "judge-standalone-dpo-${JUDGE_MODEL_SLUG}-beta${JUDGE_BETA}-seed${SEED}" \
      "${PIPELINE_CKPT_ARGS[@]}" \
      "${PIPELINE_RESTART_ARGS[@]}" \
      --skip-steps 1
    ;;

  judge_gptoss_standalone_dpo)
    # GPT-OSS judge-only condition: rejecteds = bad_match samples only, no hard mislabels.
    # GPT-OSS analogue of judge_standalone_dpo for a clean standalone comparison.
    GPTOSS_JUDGE_MODEL="${GPTOSS_JUDGE_MODEL:-openai/gpt-oss-120b}"
    GPTOSS_JUDGE_MODEL_SLUG="${GPTOSS_JUDGE_MODEL//\//_}"
    GPTOSS_JUDGE_TP="${GPTOSS_JUDGE_TP:-1}"

    python scripts/dpo/generate_dpo_pairs.py \
      --from-samples "${CANONICAL_SAMPLES}" \
      --adapter-path "${BASE_SFT_ADAPTER}" \
      --base-model "${BASE_MODEL}" \
      --output-dir "${JUDGE_GPTOSS_STANDALONE_PAIRS_DIR}" \
      --intent-filter \
      --judge-only \
      --judge-model "${GPTOSS_JUDGE_MODEL}" \
      --judge-tensor-parallel "${GPTOSS_JUDGE_TP}" \
      --max-model-len "${MAX_MODEL_LEN}"

    python scripts/dpo/run_preference_pipeline.py \
      --adapter-path "${BASE_SFT_ADAPTER}" \
      --base-model "${BASE_MODEL}" \
      --pairs-dir "${JUDGE_GPTOSS_STANDALONE_PAIRS_DIR}" \
      --balanced-pairs-dir "${JUDGE_GPTOSS_STANDALONE_BALANCED_DIR}" \
      --dpo-output-dir "${JUDGE_GPTOSS_STANDALONE_DPO_OUTPUT}" \
      --epochs "${JUDGE_EPOCHS}" \
      --learning-rate "${LEARNING_RATE}" \
      --batch-size "${BATCH_SIZE}" \
      --grad-accum "${GRAD_ACCUM}" \
      --dpo-beta "${JUDGE_BETA}" \
      --attn-implementation "${ATTN_IMPL}" \
      --seed "${SEED}" \
      --wandb-project "${WANDB_PROJECT}" \
      --wandb-run "judge-gptoss-standalone-dpo-${GPTOSS_JUDGE_MODEL_SLUG}-beta${JUDGE_BETA}-seed${SEED}" \
      "${PIPELINE_CKPT_ARGS[@]}" \
      "${PIPELINE_RESTART_ARGS[@]}" \
      --skip-steps 1
    ;;

  judge_decent_dpo)
    # Judge-only condition with bad_match + decent_match rejecteds.
    # Requires judge_standalone_dpo to have run first (reuses its dpo_pairs_decent.jsonl).
    python scripts/dpo/run_preference_pipeline.py \
      --adapter-path "${BASE_SFT_ADAPTER}" \
      --base-model "${BASE_MODEL}" \
      --pairs-dir "${JUDGE_STANDALONE_PAIRS_DIR}" \
      --pairs-filename "dpo_pairs_decent.jsonl" \
      --balanced-pairs-dir "${JUDGE_DECENT_BALANCED_DIR}" \
      --dpo-output-dir "${JUDGE_DECENT_DPO_OUTPUT}" \
      --epochs "${JUDGE_EPOCHS}" \
      --learning-rate "${LEARNING_RATE}" \
      --batch-size "${BATCH_SIZE}" \
      --grad-accum "${GRAD_ACCUM}" \
      --dpo-beta "${JUDGE_BETA}" \
      --attn-implementation "${ATTN_IMPL}" \
      --seed "${SEED}" \
      --wandb-project "${WANDB_PROJECT}" \
      --wandb-run "judge-decent-dpo-${JUDGE_MODEL_SLUG}-beta${JUDGE_BETA}-seed${SEED}" \
      "${PIPELINE_CKPT_ARGS[@]}" \
      "${PIPELINE_RESTART_ARGS[@]}" \
      --skip-steps 1
    ;;

  union_decent_dpo)
    # Union condition with bad_match + decent_match rejecteds (hard ∪ judge decent).
    # Requires judge_dpo to have run first (reuses its dpo_pairs_decent.jsonl).
    python scripts/dpo/run_preference_pipeline.py \
      --adapter-path "${BASE_SFT_ADAPTER}" \
      --base-model "${BASE_MODEL}" \
      --pairs-dir "${JUDGE_PAIRS_DIR}" \
      --pairs-filename "dpo_pairs_decent.jsonl" \
      --balanced-pairs-dir "${UNION_DECENT_BALANCED_DIR}" \
      --dpo-output-dir "${UNION_DECENT_DPO_OUTPUT}" \
      --epochs "${JUDGE_EPOCHS}" \
      --learning-rate "${LEARNING_RATE}" \
      --batch-size "${BATCH_SIZE}" \
      --grad-accum "${GRAD_ACCUM}" \
      --dpo-beta "${JUDGE_BETA}" \
      --attn-implementation "${ATTN_IMPL}" \
      --seed "${SEED}" \
      --wandb-project "${WANDB_PROJECT}" \
